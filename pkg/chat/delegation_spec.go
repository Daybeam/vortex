package chat

import (
	"fmt"
	"log"
	"os"
	"strings"
	"sync"

	"github.com/daybeam/vortex/core"
)

// DelegationSpecEnv switches the verbatim-spec append on the delegation path.
// Default on: the append is strictly additive information, and the defect it
// fixes is silent. "off"/"none"/"0" restores the pre-v74 behaviour so an arm
// can isolate it.
const DelegationSpecEnv = "VORTEX_DELEGATION_SPEC"

// DelegationSpecPreamble frames the appended text. It has to do two jobs at
// once: make the text authoritative for constraints, and keep the delegated
// scope from expanding to the whole task — the parent usually delegates a
// slice, and a verbatim task body reads like a work order if unattended.
const DelegationSpecPreamble = "[DELEGATION SPEC] The sections below are copied verbatim from the task " +
	"specification this session was given. They are authoritative: where they disagree " +
	"with the summary above, they win. Your scope is what the summary asks for; these " +
	"sections are the constraints that scope must respect. `Delete: none` is literal: " +
	"do not delete, move, or rewrite the input files."

// DelegationSpecBodyOmitted replaces the body when it is too large to append.
// It has to say three things: the body is missing, why, and what to do instead
// — the last one because "read it from the workspace" is a different action
// from "read it here", and a sub-agent that assumes the text is absent will
// otherwise re-derive it from nothing.
const DelegationSpecBodyOmitted = "[DELEGATION SPEC] The task text is too large to re-append " +
	"(%d bytes > %d cap), so it is not repeated here. The summary above stands as the task " +
	"statement; read the source material from the workspace instead of expecting it below."

// DelegationSpecMaxBytes caps the instruction body that gets re-appended. It is
// a context-safety bound, not a policy: 16 KiB is ~4k tokens (EstimateTokens is
// runes/4), about 3% of a 128k window and well under the smallest usable budget
// this engine has run with. Every benchmark task prompt measured so far is
// ~1.1–2.0 KB, so the cap never fires there — it exists for the chat case, where
// the last user message can be a pasted legal document or a file dump and the
// sub-agent, unlike this session, does not have room for it twice.
const DelegationSpecMaxBytes = 16 << 10

// DelegationContractMaxBytes caps the contract section. It is generated by the
// harness (~400 bytes), so this only ever fires on a malformed prompt; the
// bound is here so a hand-written prompt cannot smuggle a document into the
// section that is supposed to be a short list.
const DelegationContractMaxBytes = 4 << 10

// DelegationSpecEnabled reports whether the append is on. Unset means on.
//
// The parent's summary of a task is lossy in a way that no amount of prompting
// fixes: in the v73 batch, "with a human-readable local date and start/end
// time" became "human-readable" in 5 of 5 delegation prompts, and every one of
// those runs then wrote a start-only local-time value that the grader rejects
// (iron law 178). The engine already holds the original text; handing it over
// costs ~400 tokens and removes the re-encoding step entirely.
func DelegationSpecEnabled() bool {
	switch strings.ToLower(strings.TrimSpace(os.Getenv(DelegationSpecEnv))) {
	case "off", "none", "0", "false":
		return false
	default:
		return true
	}
}

var delegationSpecLogged sync.Once

// LogDelegationSpecOnce prints the value in force once per process. A flag
// that is silently misspelled is indistinguishable from the default (→107).
func LogDelegationSpecOnce() {
	delegationSpecLogged.Do(func() {
		log.Printf("[config] %s=%q delegation_spec=%v", DelegationSpecEnv,
			os.Getenv(DelegationSpecEnv), DelegationSpecEnabled())
	})
}

// delegatedPromptWithSpec appends the verbatim task specification and the
// workspace-change contract to a delegation prompt.
//
// Returns prompt unchanged (byte for byte) when there is nothing to add: no
// task prompt was captured, the prompt carries no contract, the two sections
// are empty, or the caller already pasted the contract itself. The last case
// matters because a duplicate "Delete: none" reads like a different rule from
// the one above it.
func (h *ChatHarness) delegatedPromptWithSpec(prompt string) string {
	if h == nil || !DelegationSpecEnabled() {
		return prompt
	}
	spec := h.taskPrompt
	if strings.TrimSpace(spec) == "" {
		return prompt
	}
	if strings.Contains(prompt, core.WorkspaceContractHeader) {
		return prompt
	}
	instruction, contract := core.SpecSections(spec)
	// Size guard. The append can only duplicate text that is already in this
	// session's context, so it cannot make a prompt larger than the model has
	// already accepted — but it can make the *sub-agent's* prompt that large,
	// and a sub-agent that could have worked from a two-paragraph summary now
	// has to carry the whole document. Above the cap the body is dropped and
	// the summary stands: a summary that is too lossy is a bad answer, an
	// unloadable prompt is no answer at all.
	bodyOmitted := len(instruction) > DelegationSpecMaxBytes
	if bodyOmitted {
		log.Printf("[delegation-spec] task body omitted: %d bytes > %d cap", len(instruction), DelegationSpecMaxBytes)
		instruction = ""
	}
	if len(contract) > DelegationContractMaxBytes {
		log.Printf("[delegation-spec] contract section omitted: %d bytes > %d cap", len(contract), DelegationContractMaxBytes)
		contract = ""
	}
	if strings.TrimSpace(instruction) == "" && strings.TrimSpace(contract) == "" && !bodyOmitted {
		return prompt
	}
	var b strings.Builder
	b.WriteString(strings.TrimRight(prompt, " \t\n"))
	b.WriteString("\n\n")
	b.WriteString(DelegationSpecPreamble)
	if bodyOmitted {
		b.WriteString(fmt.Sprintf("\n\n"+DelegationSpecBodyOmitted, len(spec), DelegationSpecMaxBytes))
	}
	if strings.TrimSpace(instruction) != "" {
		b.WriteString("\n\n### Verbatim — task specification (as given to this session)\n\n")
		b.WriteString(instruction)
	}
	if strings.TrimSpace(contract) != "" {
		b.WriteString("\n\n### Verbatim — workspace change contract\n\n")
		b.WriteString(contract)
	}
	b.WriteString("\n")
	return b.String()
}
